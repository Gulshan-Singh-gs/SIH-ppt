class DualEngineLLM:
    """
    Unified LLM Client providing local open-weight inference for sovereign air-gapped government compliance.
    """

    def __init__(
        self,
        ollama_url: str = "http://127.0.0.1:11434",
        local_model: str = "llama3:latest",
    ):
        self.ollama_url = ollama_url
        self.local_model = local_model

    def get_active_engine_info(self) -> Dict[str, Any]:
        """Returns availability and status of configured engines."""
        return {
            "local_sovereign": {
                "url": self.ollama_url,
                "model": self.local_model,
                "tier": "100% On-Premise Air-Gapped (BharatGPT/Llama-3)",
                "cost": "$0 (Local CPU/GPU)",
            },
            "preferred_engine": "local",
        }

    async def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
        max_tokens: int = 4096,
        engine_override: Optional[str] = None,
    ) -> str:
        """
        Generate text response using local open-weight LLM with deterministic fallback.
        """
        # Try Local Ollama
        try:
            return await self._call_ollama(prompt, system_prompt, temperature, max_tokens)
        except Exception as e:
            logger.warning(f"Local Ollama generation failed: {e}. Using local fallback synthesizer...")

        # Fallback to local deterministic synthesizer
        return self._generate_autonomous_fallback(prompt, system_prompt)

    async def _call_ollama(
        self, prompt: str, system_prompt: Optional[str], temperature: float, max_tokens: int
    ) -> str:
        """Call local Ollama server running on-premise."""
        full_prompt = f"{system_prompt}\n\n{prompt}" if system_prompt else prompt
        payload = {
            "model": self.local_model,
            "prompt": full_prompt,
            "stream": False,
            "options": {
                "temperature": temperature,
                "num_predict": max_tokens,
            },
        }
        async with httpx.AsyncClient(timeout=60.0) as client:
            resp = await client.post(f"{self.ollama_url}/api/generate", json=payload)
            resp.raise_for_status()
            return resp.json().get("response", "")

